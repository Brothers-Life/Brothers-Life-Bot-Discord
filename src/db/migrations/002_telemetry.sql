-- FiveM telemetry (port of bl-panel-api): data sent by the bl_telemetry resource (POST /v1/batch),
-- scraped from the FiveM server (/perf/, /dynamic.json) and the alerts raised from it.
-- Tables keep the shapes of bl-panel-api/schema.sql, prefixed with tel_ (the bot already has events and sessions).

CREATE TABLE IF NOT EXISTS tel_events (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	type TEXT NOT NULL,
	subtype TEXT,
	citizenid TEXT,
	player_name TEXT,
	src INT,
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_events_ts ON tel_events (ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_events_type_ts ON tel_events (type, ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_events_cid_ts ON tel_events (citizenid, ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_events_subtype_ts ON tel_events (subtype, ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_events_flow_from ON tel_events ((data->>'from_cid'), ts DESC) WHERE subtype = 'bank_flow';
CREATE INDEX IF NOT EXISTS idx_tel_events_flow_to ON tel_events ((data->>'to_cid'), ts DESC) WHERE subtype = 'bank_flow';

CREATE TABLE IF NOT EXISTS tel_economy_snapshots (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	player_count INT,
	chars_total INT,
	total_cash BIGINT,
	total_bank BIGINT,
	total_crypto NUMERIC,
	society_total BIGINT,
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_econ_ts ON tel_economy_snapshots (ts DESC);

CREATE TABLE IF NOT EXISTS tel_player_snapshots (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	citizenid TEXT NOT NULL,
	name TEXT,
	job TEXT,
	job_grade INT,
	gang TEXT,
	cash BIGINT,
	bank BIGINT,
	crypto NUMERIC,
	online BOOLEAN DEFAULT false,
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_psnap_cid_ts ON tel_player_snapshots (citizenid, ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_psnap_ts ON tel_player_snapshots (ts DESC);

CREATE TABLE IF NOT EXISTS tel_purchases (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	citizenid TEXT,
	player_name TEXT,
	shop TEXT,
	item TEXT,
	label TEXT,
	qty INT DEFAULT 1,
	unit_price NUMERIC,
	total NUMERIC,
	currency TEXT DEFAULT 'cash',
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_purch_ts ON tel_purchases (ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_purch_cid ON tel_purchases (citizenid, ts DESC);

CREATE TABLE IF NOT EXISTS tel_deaths (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	citizenid TEXT,
	player_name TEXT,
	cause TEXT,
	killer_cid TEXT,
	killer_name TEXT,
	weapon TEXT,
	x REAL, y REAL, z REAL,
	screenshot_url TEXT,
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_deaths_ts ON tel_deaths (ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_deaths_cid ON tel_deaths (citizenid, ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_deaths_killer ON tel_deaths (killer_cid, ts DESC);

-- license: only used to join a session to the character loaded afterwards and to find linked characters;
-- never returned to the panel
CREATE TABLE IF NOT EXISTS tel_sessions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	citizenid TEXT,
	player_name TEXT,
	license TEXT,
	src INT,
	start_ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	end_ts TIMESTAMPTZ,
	duration_min REAL,
	drop_reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_tel_sessions_cid ON tel_sessions (citizenid, start_ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_sessions_start ON tel_sessions (start_ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_sessions_license ON tel_sessions (license);

CREATE TABLE IF NOT EXISTS tel_vehicles_owned (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	citizenid TEXT,
	owner_name TEXT,
	plate TEXT,
	model TEXT,
	garage TEXT,
	state INT,
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_veh_ts ON tel_vehicles_owned (ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_veh_cid ON tel_vehicles_owned (citizenid, ts DESC);

CREATE TABLE IF NOT EXISTS tel_admin_actions (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	action TEXT,
	admin_name TEXT,
	target_cid TEXT,
	target_name TEXT,
	reason TEXT,
	duration TEXT,
	data JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_admin_ts ON tel_admin_actions (ts DESC);

CREATE TABLE IF NOT EXISTS tel_server_logs (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	channel TEXT,
	level TEXT,
	source TEXT,
	line TEXT,
	labels JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_slogs_ts ON tel_server_logs (ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_slogs_chan ON tel_server_logs (channel, ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_slogs_level_ts ON tel_server_logs (level, ts DESC);

CREATE TABLE IF NOT EXISTS tel_perf_metrics (
	ts TIMESTAMPTZ NOT NULL,
	metric TEXT NOT NULL,
	thread TEXT,
	le DOUBLE PRECISION,
	value DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS idx_tel_perf_ts ON tel_perf_metrics (metric, ts DESC);

CREATE TABLE IF NOT EXISTS tel_alerts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	kind TEXT NOT NULL,
	severity TEXT NOT NULL DEFAULT 'warn',
	title TEXT NOT NULL,
	detail TEXT,
	citizenid TEXT,
	data JSONB,
	notified BOOLEAN DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_tel_alerts_ts ON tel_alerts (ts DESC);
CREATE INDEX IF NOT EXISTS idx_tel_alerts_cid ON tel_alerts (citizenid, ts DESC);

CREATE TABLE IF NOT EXISTS tel_db_snapshots (
	name TEXT PRIMARY KEY,
	label TEXT,
	kind TEXT,
	pos INT,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	columns JSONB,
	rows JSONB
);

CREATE TABLE IF NOT EXISTS tel_db_table_stats (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	table_name TEXT NOT NULL,
	rows BIGINT,
	bytes BIGINT
);
CREATE INDEX IF NOT EXISTS idx_tel_dbstats_ts ON tel_db_table_stats (ts DESC);

-- Orders of the panel (announcements) picked up by bl_telemetry
CREATE TABLE IF NOT EXISTS tel_commands (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	type TEXT NOT NULL,
	payload JSONB,
	author TEXT,
	status TEXT NOT NULL DEFAULT 'pending', -- pending | sent | done | failed | expired
	sent_at TIMESTAMPTZ,
	done_at TIMESTAMPTZ,
	result TEXT
);
CREATE INDEX IF NOT EXISTS idx_tel_commands_status ON tel_commands (status, id);

CREATE TABLE IF NOT EXISTS tel_perf_windows (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	window_s INT,
	players_online INT,
	n INT,
	fps REAL,
	fps_min REAL,
	worst REAL,
	hist JSONB,
	entities JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_perf_windows_ts ON tel_perf_windows (ts DESC);

CREATE TABLE IF NOT EXISTS tel_perf_buckets (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	kind TEXT NOT NULL, -- zone | interior | player
	key TEXT NOT NULL,
	label TEXT,
	n INT, fps REAL, fps_min REAL, worst REAL, obj REAL, peds REAL, veh REAL,
	x REAL, y REAL, z REAL, players INT, ping INT
);
CREATE INDEX IF NOT EXISTS idx_tel_perf_buckets_kind_ts ON tel_perf_buckets (kind, ts DESC);

CREATE TABLE IF NOT EXISTS tel_profiler_runs (
	ts TIMESTAMPTZ NOT NULL DEFAULT now(),
	span_ms REAL,
	total_ms REAL,
	frames INT,
	resources JSONB,
	top JSONB
);
CREATE INDEX IF NOT EXISTS idx_tel_profiler_runs_ts ON tel_profiler_runs (ts DESC);

-- Categories of the links between servers (legal businesses, illegal groups, staff...) and boards made of
-- several messages (one card with the server's logo per server: 10 embeds at most per message).
CREATE TABLE IF NOT EXISTS server_link_categories (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	emoji TEXT NOT NULL DEFAULT '',
	color TEXT,
	position BIGINT NOT NULL DEFAULT 0,
	created_at BIGINT NOT NULL
);

ALTER TABLE server_link_guilds ADD COLUMN IF NOT EXISTS category_id BIGINT;
-- Ids of the messages after the first one (discord_id)
ALTER TABLE server_link_boards ADD COLUMN IF NOT EXISTS extra_ids TEXT NOT NULL DEFAULT '[]';

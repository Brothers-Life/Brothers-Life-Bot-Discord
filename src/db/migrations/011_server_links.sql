-- Links between the servers of the network: how each server is presented (name, text, invitation)
-- and the messages ("boards") listing the other servers, kept up to date in a channel.
CREATE TABLE IF NOT EXISTS server_link_guilds (
	guild_id TEXT PRIMARY KEY,
	-- 0: never shown in a board (staff servers...)
	listed BIGINT NOT NULL DEFAULT 0,
	label TEXT NOT NULL DEFAULT '',
	description TEXT NOT NULL DEFAULT '',
	emoji TEXT NOT NULL DEFAULT '',
	-- auto: the bot creates a permanent invitation; manual: a link typed in the panel (vanity URL...)
	invite_mode TEXT NOT NULL DEFAULT 'auto' CHECK (invite_mode IN ('auto', 'manual')),
	invite_channel_id TEXT,
	invite_code TEXT,
	invite_error TEXT,
	invite_checked_at BIGINT,
	position BIGINT NOT NULL DEFAULT 0,
	updated_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS server_link_boards (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	guild_id TEXT NOT NULL,
	channel_id TEXT NOT NULL,
	enabled BIGINT NOT NULL DEFAULT 1,
	-- { payload: { content, embed }, line, compact, scope, guildIds, includeSelf, buttons, repost }
	config TEXT NOT NULL,
	discord_id TEXT,
	last_hash TEXT,
	last_error TEXT,
	synced_at BIGINT,
	-- Claimed while a process posts or edits the message (the panel and the periodic task never post twice)
	syncing_at BIGINT,
	created_by TEXT NOT NULL,
	created_at BIGINT NOT NULL,
	updated_at BIGINT NOT NULL
);

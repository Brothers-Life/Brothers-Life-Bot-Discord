-- Takeovers of businesses and illegal groups: the staff lists what is available, people register, one is chosen
CREATE TABLE takeovers (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	guild_id TEXT NOT NULL,
	category TEXT NOT NULL CHECK (category IN ('business', 'illegal')),
	name TEXT NOT NULL,
	description TEXT NOT NULL DEFAULT '',
	mode TEXT NOT NULL CHECK (mode IN ('form', 'simple')),
	open BOOLEAN NOT NULL DEFAULT FALSE,
	interview_at BIGINT,
	convoked_at BIGINT,
	winner_id TEXT,
	winner_name TEXT,
	finished_at BIGINT,
	created_at BIGINT NOT NULL
);

CREATE INDEX takeovers_by_guild ON takeovers (guild_id, finished_at);

CREATE TABLE takeover_entries (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	takeover_id BIGINT NOT NULL,
	guild_id TEXT NOT NULL,
	user_id TEXT NOT NULL,
	user_name TEXT,
	answers TEXT NOT NULL DEFAULT '[]',
	status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'removed')),
	dm_status TEXT CHECK (dm_status IN ('sent', 'failed')),
	created_at BIGINT NOT NULL,
	UNIQUE (takeover_id, user_id),
	FOREIGN KEY (takeover_id) REFERENCES takeovers (id) ON DELETE CASCADE
);

CREATE INDEX takeover_entries_by_guild ON takeover_entries (guild_id, takeover_id);

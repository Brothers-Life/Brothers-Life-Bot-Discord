-- Takeovers: categories inside each type (business, illegal group) and a free order for everything
CREATE TABLE takeover_groups (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	guild_id TEXT NOT NULL,
	category TEXT NOT NULL CHECK (category IN ('business', 'illegal')),
	name TEXT NOT NULL,
	emoji TEXT,
	position INTEGER NOT NULL DEFAULT 0,
	created_at BIGINT NOT NULL
);

CREATE INDEX takeover_groups_by_guild ON takeover_groups (guild_id, category, position);

ALTER TABLE takeovers ADD COLUMN group_id BIGINT REFERENCES takeover_groups (id) ON DELETE SET NULL;
ALTER TABLE takeovers ADD COLUMN position INTEGER NOT NULL DEFAULT 0;

-- Keeps the order already shown on Discord: oldest first
UPDATE takeovers t SET position = o.n
FROM (SELECT id, row_number() OVER (PARTITION BY guild_id, category ORDER BY id) AS n FROM takeovers) o
WHERE o.id = t.id;
